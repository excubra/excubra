const key = (slug) => "si" + slug.charAt(0).toUpperCase() + slug.slice(1)

const icons = {}
const rules = []
const missing = []
for (const [slug, pattern] of WANT) {
  const icon = si[key(slug)] ?? Object.values(si).find((i) => i && i.slug === slug)
  if (!icon) {
    missing.push(slug)
    continue
  }
  icons[slug] = { t: icon.title, c: "#" + icon.hex, d: icon.path }
  rules.push([pattern, slug])
}
if (missing.length) console.error("not in simple-icons, skipped:", missing.join(", "))

const out = `// GENERATED by scripts/gen-vendor-marks.mjs — do not edit by hand.
//
// Paths from simple-icons (CC0-1.0), vendored like every other asset: the console
// may sit in an overlay without internet (ADR-0008). The brands belong to their
// owners and are used here to name the device they stand for, nothing else.
// Vendors simple-icons does not carry get a monogram in vendor-mark.tsx.

export type Icon = { t: string; c: string; d: string }

export const icons: Record<string, Icon> = {
${Object.entries(icons).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join("\n")}
}

/** What an OUI vendor string may look like → which mark to draw. First match wins. */
export const rules: [RegExp, string][] = [
${rules.map(([p, s]) => `  [/${p}/, ${JSON.stringify(s)}],`).join("\n")}
]
`
writeFileSync(new URL("../src/components/vendor-marks.generated.ts", import.meta.url), out)
console.log(`wrote ${Object.keys(icons).length} marks, ${rules.length} rules`)
